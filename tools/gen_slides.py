import shutil
import socket
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import config as apconfig  # noqa: E402
import slides_data  # noqa: E402  (engagement -> Report mapping, same dir)


# ───────────────────────── tool-presence guarding ─────────────────────────
def _find_chrome() -> str | None:
    """Resolve a Chrome/Chromium binary: config/env > known paths > PATH."""
    b = apconfig.get_bin("chrome", env="AP_BIN_CHROME")
    if b:
        return b
    mac = [
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Chromium.app/Contents/MacOS/Chromium",
        "/Applications/Google Chrome Canary.app/Contents/MacOS/Google Chrome Canary",
    ]
    for p in mac:
        if os.path.exists(p):
            return p
    for name in ("google-chrome", "google-chrome-stable", "chromium", "chromium-browser", "chrome"):
        w = shutil.which(name)
        if w:
            return w
    return None


def preflight(slidegen: Path) -> tuple[dict, list[str]]:
    """Return (resolved_bins, missing_messages). Empty list == all present."""
    missing: list[str] = []
    node = apconfig.get_bin("node", env="AP_BIN_NODE")
    npm = apconfig.get_bin("npm", env="AP_BIN_NPM")
    chrome = _find_chrome()
    if not slidegen.is_dir():
        missing.append(
            f"SlideGen not found at {slidegen}. Clone it:\n"
            f"    git clone https://github.com/net-runners-com/SlideGen {slidegen}"
        )
    if not node:
        missing.append("node not found (needed to run SlideGen). Install Node.js >= 18, "
                       "or set bins.node in config.toml / AP_BIN_NODE.")
    if not npm:
        missing.append("npm not found (needed to install SlideGen deps). "
                       "Install Node.js, or set bins.npm / AP_BIN_NPM.")
    if not chrome:
        missing.append("Google Chrome / Chromium not found (needed to render slides "
                       "headless). Install Chrome, or set bins.chrome / AP_BIN_CHROME.")
    try:
        import reportlab  # noqa: F401
    except Exception:
        missing.append("python 'reportlab' not installed (needed to assemble the PDF). "
                       "pip install reportlab")
    try:
        import PIL  # noqa: F401
    except Exception:
        missing.append("python 'Pillow' not installed (needed to flatten slide PNGs). "
                       "pip install Pillow")
    return {"node": node, "npm": npm, "chrome": chrome}, missing


# ───────────────────────── free-port helpers ─────────────────────────
def _free_port() -> int:
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    s.bind(("127.0.0.1", 0))
    p = s.getsockname()[1]
    s.close()
    return p


# ───────────────────────── SlideGen source injection ─────────────────────────
INDEX_IMPORT = "src/reports/index.ts"
SLIDES_INDEX = "src/slides/index.ts"


def inject_report(slidegen: Path, report_ts: str, slug: str) -> list[Path]:
    """Write the generated report + rewrite reports/index.ts. Returns files to clean."""
    created: list[Path] = []
    rep = slidegen / "src" / "reports" / f"{slug}.local.ts"
    rep.write_text(report_ts, encoding="utf-8")
    created.append(rep)
    (slidegen / INDEX_IMPORT).write_text(
        "/** AUTO-GENERATED by tools/gen_slides.py — selects the engagement report. */\n"
        f"import {{ report }} from './{slug}.local'\n\n"
        "export const R = report\n",
        encoding="utf-8",
    )
    return created


def inject_plugin_slide(slidegen: Path, slide_ts: str) -> list[Path]:
    """Write the plugin-table slide and append it to the DECK; bump page totals."""
    created: list[Path] = []
    sl = slidegen / "src" / "slides" / "plugins.local.ts"
    sl.write_text(slide_ts, encoding="utf-8")
    created.append(sl)

    idx = slidegen / SLIDES_INDEX
    src = idx.read_text(encoding="utf-8")
    src = src.replace(
        "import { s8 } from './s8'",
        "import { s8 } from './s8'\nimport { pluginsSlide } from './plugins.local'",
    )
    src = src.replace(
        "export const DECK: Slide[] = [s1, s2, s3, s4, s5, s6, s7, s8]",
        "export const DECK: Slide[] = [s1, s2, s3, s4, s5, s6, s7, s8, pluginsSlide]",
    )
    idx.write_text(src, encoding="utf-8")

    # page total "/ 08" -> "/ 09" across every slide (the plugin slide emits "/ 09" itself)
    for f in (slidegen / "src" / "slides").glob("s*.ts"):
        t = f.read_text(encoding="utf-8")
        if "/ 08" in t:
            f.write_text(t.replace("/ 08", "/ 09"), encoding="utf-8")
    return created


def patch_rank_text(slidegen: Path, rank_now: str, rank_worst: str) -> None:
    """s5.ts bakes a 'C判定 / 最悪A' example into its explanatory note. Make it
    agree with the engagement's derived ranks (restorable via git checkout)."""
    s5 = slidegen / "src" / "slides" / "s5.ts"
    if not s5.is_file():
        return
    t = s5.read_text(encoding="utf-8")
    t = t.replace("C判定の読み違いを防ぐために", f"{rank_now}判定の読み違いを防ぐために")
    t = t.replace("Cは安全判定ではありません", f"{rank_now}は安全判定ではありません")
    t = t.replace("同じレポート内で最悪Aへ変わります", f"同じレポート内で最悪{rank_worst}へ変わります")
    s5.write_text(t, encoding="utf-8")


def restore_slidegen(slidegen: Path, created: list[Path]) -> None:
    """Revert tracked edits via git and remove generated untracked files."""
    try:
        subprocess.run(["git", "-C", str(slidegen), "checkout", "--", "src"],
                       check=False, capture_output=True)
    except Exception:
        pass
    for p in created:
        try:
            p.unlink(missing_ok=True)
        except Exception:
            pass


# ───────────────────────── headless render ─────────────────────────
CAPTURE_JS = r"""
// CDP headless capture: navigate each slide, read canvas.toDataURL(), write PNG.
import { writeFileSync } from 'node:fs'
const cdpPort = Number(process.argv[2])
const viteUrl = process.argv[3]
const outDir = process.argv[4]
const nSlides = Number(process.argv[5])
const base = `http://127.0.0.1:${cdpPort}`
const list = await (await fetch(`${base}/json/list`)).json()
const page = list.find((t) => t.type === 'page')
if (!page) { console.error('NO_PAGE_TARGET'); process.exit(2) }
const ws = new WebSocket(page.webSocketDebuggerUrl)
await new Promise((r) => (ws.onopen = r))
let id = 0; const pending = new Map()
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } }
const send = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })) })
const evalJS = async (expr) => {
  const r = await send('Runtime.evaluate', { expression: expr, awaitPromise: true, returnByValue: true })
  if (r.result?.exceptionDetails) throw new Error(JSON.stringify(r.result.exceptionDetails))
  return r.result?.result?.value
}
await send('Page.enable'); await send('Runtime.enable')
await send('Page.navigate', { url: `${viteUrl}/?t=${Date.now()}#1` })
await new Promise((r) => setTimeout(r, 9000))
const ready = await evalJS(`document.fonts.ready.then(()=>document.querySelector('canvas.lower-canvas')!=null)`)
if (!ready) { console.error('CANVAS_NOT_READY'); process.exit(3) }
const saved = []
for (let n = 1; n <= nSlides; n++) {
  await evalJS(`location.hash='#${n}'`)
  await new Promise((r) => setTimeout(r, 1500))
  const data = await evalJS(`(()=>{const c=document.querySelector('canvas.lower-canvas');return c?c.toDataURL('image/png'):null})()`)
  if (!data) { console.error(`slide ${n}: NO_CANVAS`); continue }
  const buf = Buffer.from(data.split(',')[1], 'base64')
  const f = `${outDir}/slide-${String(n).padStart(2, '0')}.png`
  writeFileSync(f, buf); saved.push(f)
  console.log(`slide ${n}: ${buf.length} bytes`)
}
ws.close()
console.log('SAVED ' + saved.length)
"""


def render_headless(bins: dict, slidegen: Path, n_slides: int, png_dir: Path,
                    work: Path, verbose: bool) -> list[Path]:
    """Start vite + headless Chrome, capture n_slides PNGs. Cleans up its procs."""
    vite_port = _free_port()
    cdp_port = _free_port()
    vite_url = f"http://localhost:{vite_port}"
    chrome_prof = work / "chrome-prof"
    chrome_prof.mkdir(parents=True, exist_ok=True)
    capture = work / "capture.mjs"
    capture.write_text(CAPTURE_JS, encoding="utf-8")
    vite_log = open(work / "vite.log", "w")
    chrome_log = open(work / "chrome.log", "w")
    vite_proc = chrome_proc = None
    try:
        vite_proc = subprocess.Popen(
            [bins["node"], str(slidegen / "node_modules" / ".bin" / "vite"),
             "--port", str(vite_port), "--strictPort"],
            cwd=str(slidegen), stdout=vite_log, stderr=subprocess.STDOUT)
        # wait for vite (binds "localhost" -> may be IPv6 ::1, so resolve via name)
        for _ in range(60):
            try:
                socket.create_connection(("localhost", vite_port), timeout=0.5).close()
                break
            except OSError:
                if vite_proc.poll() is not None:
                    raise RuntimeError("vite dev server exited early (see vite.log)")
                time.sleep(0.25)
        else:
            raise RuntimeError("vite dev server did not start (see vite.log)")

        chrome_proc = subprocess.Popen(
            [bins["chrome"], "--headless=new", "--disable-gpu",
             f"--remote-debugging-port={cdp_port}", f"--user-data-dir={chrome_prof}",
             "--no-first-run", "--no-default-browser-check", "about:blank"],
            stdout=chrome_log, stderr=subprocess.STDOUT)
        for _ in range(40):
            try:
                socket.create_connection(("127.0.0.1", cdp_port), timeout=0.5).close()
                break
            except OSError:
                time.sleep(0.25)
        else:
            raise RuntimeError("headless Chrome CDP endpoint did not open (see chrome.log)")

        proc = subprocess.run(
            [bins["node"], str(capture), str(cdp_port), vite_url, str(png_dir), str(n_slides)],
            capture_output=True, text=True, timeout=180)
        if verbose or proc.returncode != 0:
            sys.stderr.write(proc.stdout + proc.stderr)
        if proc.returncode != 0:
            raise RuntimeError(f"headless capture failed (rc={proc.returncode})")
    finally:
        for p in (chrome_proc, vite_proc):
            if p and p.poll() is None:
                p.terminate()
                try:
                    p.wait(timeout=5)
                except Exception:
                    p.kill()
        vite_log.close()
        chrome_log.close()
    pngs = sorted(png_dir.glob("slide-*.png"))
    return pngs


def build_pdf(pngs: list[Path], out: Path) -> None:
    from PIL import Image
    from reportlab.pdfgen import canvas as pdfcanvas
    from reportlab.lib.utils import ImageReader

    W, H = 2048, 1152
    out.parent.mkdir(parents=True, exist_ok=True)
    c = pdfcanvas.Canvas(str(out), pagesize=(W, H))
    for png in pngs:
        im = Image.open(png).convert("RGBA")
        bg = Image.new("RGB", im.size, (10, 15, 24))  # navyDeep, in case of alpha
        bg.paste(im, mask=im.split()[3])
        c.drawImage(ImageReader(bg), 0, 0, width=W, height=H)
        c.showPage()
    c.save()


# ───────────────────────── main ─────────────────────────
def main() -> int:
    ap = argparse.ArgumentParser(description="Generate a slide deck from an engagement dir.")
    ap.add_argument("--engagement", required=True, help="path to a completed engagement dir")
    ap.add_argument("--out", help="output PDF path (default: <engagement>/reports/Penetration-Test-Slides.pdf)")
    ap.add_argument("--keep-png", action="store_true", help="also keep per-slide PNGs next to the PDF")
    ap.add_argument("--verbose", action="store_true", help="print render diagnostics")
    args = ap.parse_args()

    eng = Path(args.engagement).expanduser().resolve()
    if not eng.is_dir():
        print(f"[!] engagement dir not found: {eng}", file=sys.stderr)
        return 2

    slidegen = apconfig.tools_dir() / "SlideGen"
    bins, missing = preflight(slidegen)
    if missing:
        print("[!] gen_slides.py cannot run — missing dependencies:\n", file=sys.stderr)
        for m in missing:
            print("  * " + m + "\n", file=sys.stderr)
        print("    Slides are an optional output path; the engagement PDF report is "
              "unaffected.", file=sys.stderr)
        return 3

    out = Path(args.out).expanduser().resolve() if args.out else (eng / "reports" / "Penetration-Test-Slides.pdf")

    # 1. derive the Report from engagement data
    report, slug, meta = slides_data.build_report(eng)
    report_ts = slides_data.report_to_ts(report)
    plugin_slide_ts = slides_data.plugin_slide_ts(meta.get("plugins") or {}, meta.get("plugin_cves") or {})
    n_slides = 9 if plugin_slide_ts else 8

    print(f"[*] engagement: {eng.name}")
    print(f"[*] target: {report['client']['domain']}  platform: {report['platform']}")
    print(f"[*] findings mapped: {len(report['findings'])} rows  "
          f"(score now={slides_data.score_now(report)} / worst={slides_data.score_worst(report)})")
    if plugin_slide_ts:
        print(f"[*] plugin/version table: {len(meta.get('plugins') or {})} plugins")

    # 2. ensure deps
    node_modules = slidegen / "node_modules"
    if not (node_modules / ".bin" / "vite").exists():
        print("[*] installing SlideGen dependencies (first run)…")
        r = subprocess.run([bins["npm"], "install", "--no-audit", "--no-fund"],
                           cwd=str(slidegen), capture_output=not args.verbose, text=True)
        if r.returncode != 0:
            print("[!] npm install failed:\n" + (r.stderr or r.stdout or ""), file=sys.stderr)
            return 4

    # 3. inject sources (restore afterwards no matter what)
    created: list[Path] = []
    work = Path(apconfig.out_base()).parent / ".slidegen-work"
    import tempfile
    work = Path(tempfile.mkdtemp(prefix="slidegen-"))
    png_dir = work / "png"
    png_dir.mkdir(parents=True, exist_ok=True)
    try:
        created += inject_report(slidegen, report_ts, slug)
        patch_rank_text(slidegen, report["rank"]["now"], report["rank"]["worst"])
        if plugin_slide_ts:
            created += inject_plugin_slide(slidegen, plugin_slide_ts)
        print("[*] rendering headless (vite + headless Chrome)…")
        pngs = render_headless(bins, slidegen, n_slides, png_dir, work, args.verbose)
        if not pngs:
            print("[!] no slides were captured", file=sys.stderr)
            return 5
        build_pdf(pngs, out)
        print(f"[+] wrote {out}  ({out.stat().st_size // 1024} KB, {len(pngs)} slides)")
        if args.keep_png:
            png_out = out.parent / (out.stem + "_png")
            png_out.mkdir(parents=True, exist_ok=True)
            for p in pngs:
                shutil.copy2(p, png_out / p.name)
            print(f"[+] PNGs: {png_out}")
    finally:
        restore_slidegen(slidegen, created)
        shutil.rmtree(work, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
