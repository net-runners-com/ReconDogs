#!/usr/bin/env python3
"""gen_slides.py — generate a SLIDE DECK from a completed engagement dir.

Analogous to the Transilience PDF report generators (gen_site_report.py etc.),
but the output is a 16:9 presentation deck rendered by SlideGen
(tools/SlideGen — a Vite/React/Fabric.js app that draws declarative slide
nodes and exports PNG/PDF).

Pipeline (all config-driven, zero hardcoded user paths):
  1. Read the engagement's structured artifacts (findings, validated/*.json,
     recon/*.json) and derive a SlideGen `Report` object.
  2. Emit `src/reports/<slug>.local.ts` (gitignored) + an extra
     `src/slides/plugins.local.ts` plugin/version table slide, and point
     SlideGen's entrypoints at them.
  3. Run SlideGen headless: vite dev server + headless Chrome (CDP) that calls
     each slide's canvas.toDataURL() — the app's own validated export path.
  4. Assemble the per-slide PNGs into a landscape PDF.
  5. Restore SlideGen to its pristine git state.

Every external dependency is GUARDED: if SlideGen, node, npm, or Chrome is
missing the tool prints a clear, actionable message and exits non-zero
WITHOUT mutating anything (matches the existing tool-presence guarding).

Usage:
    python3 tools/gen_slides.py --engagement <dir> [--out <path>] [--keep-png]

Defaults:
    --out  <engagement>/reports/Penetration-Test-Slides.pdf
"""
from __future__ import annotations

import argparse
import json
